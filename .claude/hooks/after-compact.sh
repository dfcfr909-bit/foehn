#!/bin/bash
# 会話が要約された（SessionStart の compact）ときに、新セッションへの移行を促す。
# 残量は数値で測れないので「要約が起きた」を合図にしている（CLAUDE.md「セッションの区切り」）。
# ⚠ 出力が文脈に入ることは、開発環境では確かめられていない。入らなければ CLAUDE.md の記述が頼り。
cat <<'MSG'
【要約が起きました】会話が長くなっています。
区切りのよいところで、利用者に新セッションへの移行を提案すること。
手順は CLAUDE.md「セッションの区切り」：作業中の PR を片付けてから提案し、
新セッションの最初に貼る引き継ぎ文面（docs/status.md と未完の Issue を指すだけ）を作って渡す。
MSG
